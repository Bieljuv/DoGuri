-- ============================================================================
-- Sistema de Pedidos — Açaí do Guri · Schema Postgres (Supabase)
-- Cole TODO este arquivo no SQL Editor do Supabase para criar o banco.
--
-- Espelho FIEL do DDL SQLite (src/db.js + src/financeiro.js +
-- src/notificacoes.js), coluna a coluna. Paridades importantes:
--   * Flags são INTEGER 0/1 (aberta_manual, ativo, ativa, destaque...) —
--     o código filtra e grava com 0/1; NÃO usar BOOLEAN aqui.
--   * Colunas *_json são TEXT — o código grava JSON.stringify e lê com
--     JSON.parse da string, igual ao SQLite.
--   * Dinheiro é sempre INTEGER (centavos).
--   * INTEGER PRIMARY KEY AUTOINCREMENT -> BIGINT GENERATED BY DEFAULT AS
--     IDENTITY (BY DEFAULT permite o seed gravar a loja com id=1 explícito).
--   * created_at/updated_at: TIMESTAMPTZ DEFAULT now() (o DAL devolve
--     string ISO pro app; os relatórios usam AT TIME ZONE 'America/Sao_Paulo').
--
-- Depois de rodar este schema, NÃO precisa semear nada à mão: no primeiro
-- boot com DATABASE_URL apontando pra cá, o próprio app aplica o seed
-- (loja de exemplo + login admin/admin123 — troque a senha ao entrar).
-- ============================================================================

CREATE TABLE IF NOT EXISTS lojas (
  id BIGINT PRIMARY KEY,
  nome TEXT NOT NULL,
  slug TEXT UNIQUE,
  logo_url TEXT, capa_url TEXT,
  whatsapp TEXT, instagram TEXT, endereco_texto TEXT,
  tempo_preparo_min INTEGER DEFAULT 20,
  tempo_entrega_min INTEGER DEFAULT 40,
  pedido_minimo_centavos INTEGER DEFAULT 0,
  taxa_unica_centavos INTEGER,
  chave_pix TEXT,
  email_pedidos TEXT,
  aberta_manual INTEGER DEFAULT 1,
  horario_abre TEXT DEFAULT '13:00',
  horario_fecha TEXT DEFAULT '23:00',
  som_pedido TEXT DEFAULT 'padrao',
  pausada_ate TIMESTAMPTZ,
  proximo_numero INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loja_id BIGINT NOT NULL DEFAULT 1,
  nome TEXT NOT NULL, login TEXT UNIQUE NOT NULL,
  senha_hash TEXT NOT NULL, perfil TEXT DEFAULT 'admin', ativo INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sessoes (
  token TEXT PRIMARY KEY, usuario_id BIGINT NOT NULL,
  criado_em TIMESTAMPTZ DEFAULT now(), expira_em TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  nome TEXT NOT NULL, ordem INTEGER DEFAULT 0, ativa INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  categoria_id BIGINT, nome TEXT NOT NULL, descricao TEXT,
  foto_url TEXT, preco_base_centavos INTEGER NOT NULL DEFAULT 0,
  tipo TEXT NOT NULL DEFAULT 'simples', destaque INTEGER DEFAULT 0,
  ativo INTEGER DEFAULT 1, esgotado INTEGER DEFAULT 0, ordem INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS grupos_opcoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  nome TEXT NOT NULL, tipo_escolha TEXT NOT NULL DEFAULT 'multipla',
  minimo INTEGER DEFAULT 0, maximo INTEGER,
  obrigatorio INTEGER DEFAULT 0, excedente_vira_pago INTEGER DEFAULT 0,
  preco_excedente_centavos INTEGER DEFAULT 0, ativo INTEGER DEFAULT 1, ordem INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS opcoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, grupo_id BIGINT NOT NULL,
  nome TEXT NOT NULL, preco_adicional_centavos INTEGER NOT NULL DEFAULT 0,
  ativa INTEGER DEFAULT 1, esgotada INTEGER DEFAULT 0, ordem INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS produto_grupos (
  produto_id BIGINT NOT NULL, grupo_id BIGINT NOT NULL, ordem INTEGER DEFAULT 0,
  PRIMARY KEY (produto_id, grupo_id)
);

CREATE TABLE IF NOT EXISTS bairros (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  bairro TEXT NOT NULL, taxa_centavos INTEGER NOT NULL DEFAULT 0, ativo INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  nome TEXT, whatsapp TEXT NOT NULL, bloqueado INTEGER DEFAULT 0,
  total_pedidos INTEGER DEFAULT 0, total_cancelamentos INTEGER DEFAULT 0,
  UNIQUE(loja_id, whatsapp)
);

CREATE TABLE IF NOT EXISTS pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  numero INTEGER NOT NULL, token TEXT UNIQUE NOT NULL,
  cliente_id BIGINT, cliente_nome TEXT, cliente_whatsapp TEXT,
  tipo TEXT NOT NULL DEFAULT 'entrega',
  bairro_id BIGINT, bairro_nome TEXT, endereco_json TEXT,
  status TEXT NOT NULL DEFAULT 'NOVO',
  subtotal_centavos INTEGER NOT NULL DEFAULT 0,
  taxa_entrega_centavos INTEGER NOT NULL DEFAULT 0,
  desconto_centavos INTEGER NOT NULL DEFAULT 0,
  total_centavos INTEGER NOT NULL DEFAULT 0,
  forma_pagamento TEXT, metodo_pagamento TEXT,
  pagamento_status TEXT DEFAULT 'nao_aplicavel',
  troco_para_centavos INTEGER, observacao TEXT,
  motivo_cancelamento TEXT,
  created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(loja_id, numero)
);

CREATE TABLE IF NOT EXISTS pedido_itens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id BIGINT NOT NULL,
  produto_id BIGINT, nome_snapshot TEXT, preco_unitario_centavos INTEGER NOT NULL DEFAULT 0,
  quantidade INTEGER NOT NULL DEFAULT 1, subtotal_centavos INTEGER NOT NULL DEFAULT 0,
  observacao TEXT
);

CREATE TABLE IF NOT EXISTS pedido_item_opcoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_item_id BIGINT NOT NULL,
  grupo_nome TEXT, opcao_nome TEXT, preco_adicional_centavos INTEGER NOT NULL DEFAULT 0,
  excedente INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS pedido_status_historico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id BIGINT NOT NULL,
  de_status TEXT, para_status TEXT NOT NULL, origem TEXT DEFAULT 'painel',
  motivo TEXT, created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notificacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  pedido_id BIGINT, canal TEXT NOT NULL, -- whatsapp_cliente | whatsapp_empresa | telegram_dono
  destino TEXT, corpo TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pendente', -- pendente | enviada | falhou | simulada
  tentativas INTEGER DEFAULT 0, ultimo_erro TEXT,
  externa_ref TEXT,
  created_at TIMESTAMPTZ DEFAULT now(), enviada_em TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS impressoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id BIGINT NOT NULL,
  tipo TEXT DEFAULT 'comanda', status TEXT DEFAULT 'registrada', erro TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS config_recebimentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  meio TEXT NOT NULL UNIQUE, -- pix_presencial | cartao_presencial | dinheiro | mercadopago | asaas
  ativo INTEGER DEFAULT 0, ambiente TEXT DEFAULT 'sandbox',
  credenciais_json TEXT DEFAULT '{}',
  extra_json TEXT DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS pagamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id BIGINT NOT NULL,
  meio TEXT, provedor TEXT DEFAULT 'interno',
  valor_centavos INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'nao_aplicavel',
  externo_id TEXT, qr_texto TEXT, link_pagamento TEXT,
  ultimo_evento TEXT,
  criado_em TIMESTAMPTZ DEFAULT now(), atualizado_em TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pedidos_loja_data ON pedidos (loja_id, created_at);
CREATE INDEX IF NOT EXISTS idx_pedido_itens_pedido ON pedido_itens (pedido_id);
CREATE INDEX IF NOT EXISTS idx_notificacoes_status ON notificacoes (status);
CREATE INDEX IF NOT EXISTS idx_pagamentos_pedido ON pagamentos (pedido_id);

-- ============================================================================
-- MÓDULO FINANCEIRO (v1.1) — espelho de src/financeiro.js. As datas de
-- lançamento são TEXT YYYY-MM-DD (escolhidas pelo usuário, sem fuso).
-- ============================================================================
CREATE TABLE IF NOT EXISTS fin_lancamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  tipo TEXT NOT NULL, -- investimento | receita_manual | despesa
  categoria TEXT, descricao TEXT,
  valor_centavos INTEGER NOT NULL DEFAULT 0,
  data TEXT NOT NULL, -- YYYY-MM-DD
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fin_insumos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, loja_id BIGINT NOT NULL DEFAULT 1,
  nome TEXT NOT NULL, quantidade DOUBLE PRECISION NOT NULL DEFAULT 0, unidade TEXT,
  custo_total_centavos INTEGER NOT NULL DEFAULT 0,
  data TEXT NOT NULL, -- YYYY-MM-DD
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_fin_lancamentos_data ON fin_lancamentos (loja_id, data, tipo);
CREATE INDEX IF NOT EXISTS idx_fin_insumos_data ON fin_insumos (loja_id, data);

-- ============================================================================
-- CONFIGURAÇÕES DE NOTIFICAÇÃO (v1.3) — espelho de src/notificacoes.js.
-- Linha única (id=1): WhatsApp (Evolution API) e Telegram editáveis pelo
-- painel. Campo vazio aqui = cai pro fallback do .env no código.
